import { describe, expect, it } from "vitest";
import {
  _testExtractRussianNumeralWordsAsDigits as toDigits,
  _testNormalizeRussianPhone as normalize
} from "./salesDialog.js";

describe("Russian numeral words → digits", () => {
  it("одиночные цифры подряд: два два шесть пять три два три пять пять", () => {
    expect(toDigits("два два шесть пять три два три пять пять")).toBe("226532355");
  });

  it("группы: восемь девятьсот двадцать пять сто двадцать три сорок пять шестьдесят семь", () => {
    expect(toDigits("восемь девятьсот двадцать пять сто двадцать три сорок пять шестьдесят семь"))
      .toBe("89251234567");
  });

  it("смешанные цифры и слова: 8 девятьсот двадцать пять 123 4567", () => {
    // числительные словами после ведущей "8" → "8" не парсится (она литерал), digits = "8" + "1234567"
    // а "девятьсот двадцать пять" даст "925"
    expect(toDigits("8 девятьсот двадцать пять 123 4567")).toBe("925");
  });

  it("плюс семь девятьсот двадцать пять", () => {
    expect(toDigits("плюс семь девятьсот двадцать пять")).toBe("7925");
  });

  it("шум и слова не-числительные", () => {
    expect(toDigits("это мой номер пять три семь, запишите")).toBe("537");
  });

  it("пустая речь", () => {
    expect(toDigits("здравствуйте")).toBe("");
  });
});

describe("normalizeRussianPhone", () => {
  // Все 3 формата, как обычно диктуют клиенты:
  //   8922653…   — 11 цифр с восьмёркой
  //   +7922653…  — +7 + 10 цифр (плюс STT обычно дропает, остаётся 11 цифр с семёркой)
  //   92265323…  — 10 цифр сразу с девятки
  it("8922653… (11 цифр с восьмёркой) → +7…", () => {
    expect(normalize("89226532355")).toBe("+79226532355");
  });

  it("+7922653… (+7 + 10 цифр) → +7…", () => {
    expect(normalize("79226532355")).toBe("+79226532355");
  });

  it("92265323… (10 цифр с девятки) → +79…", () => {
    expect(normalize("9226532355")).toBe("+79226532355");
  });

  it("9 цифр → undefined (недостаточно)", () => {
    expect(normalize("226532355")).toBeUndefined();
  });

  it("12+ цифр с мусором в начале, последние 10 на 9 → +79…", () => {
    expect(normalize("12349251234567")).toBe("+79251234567");
  });
});

describe("phone format coverage", () => {
  it("словами: восемь девятьсот двадцать два…", () => {
    const digits = toDigits("восемь девятьсот двадцать два шестьсот пятьдесят три двадцать три пятьдесят пять");
    expect(normalize(digits)).toBe("+79226532355");
  });

  it("словами с +7: плюс семь девятьсот двадцать два…", () => {
    const digits = toDigits("плюс семь девятьсот двадцать два шестьсот пятьдесят три двадцать три пятьдесят пять");
    expect(normalize(digits)).toBe("+79226532355");
  });

  it("словами без префикса: девятьсот двадцать два…", () => {
    const digits = toDigits("девятьсот двадцать два шестьсот пятьдесят три двадцать три пятьдесят пять");
    expect(normalize(digits)).toBe("+79226532355");
  });

  it("одиночные цифры словами: восемь девять два два…", () => {
    const digits = toDigits("восемь девять два два шесть пять три два три пять пять");
    expect(normalize(digits)).toBe("+79226532355");
  });
});
