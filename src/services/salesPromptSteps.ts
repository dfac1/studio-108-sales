export interface SalesSessionContext {
  customerName?: string;
  customerGender?: "male" | "female";
  learnerType?: "self" | "child";
  childGender?: "boy" | "girl";
  age?: number;
  direction?: string;
  preferredCategory?: "active" | "calm" | "neutral";
  rejectedDirections?: string[];
  branch?: "Развилка" | "Озеро" | "Школьная";
  preferredTime?: "morning" | "day" | "evening";
  preferredWeekday?: "Пн" | "Вт" | "Ср" | "Чт" | "Пт" | "Сб" | "Вс";
  preferredDayType?: "weekday" | "weekend";
  selectedSlotId?: string;
  phone?: string;
  consent?: boolean;
}

export interface AvailableSlot {
  id: string;
  weekday: string;
  time: string;
  branch: string;
  direction: string;
  level?: string;
  teacher?: string;
}

export const EMPTY_CONTEXT: SalesSessionContext = {};

export function formatContext(ctx: SalesSessionContext, availableSlots?: AvailableSlot[]): string {
  const parts: string[] = [];
  if (ctx.customerName) parts.push(`Имя клиента: ${ctx.customerName}`);
  if (ctx.customerGender) parts.push(`Пол клиента: ${ctx.customerGender === "male" ? "мужской" : "женский"}`);
  if (ctx.learnerType) parts.push(`Для кого занятие: ${ctx.learnerType === "child" ? "для ребёнка" : "для клиента (взрослый)"}`);
  if (ctx.childGender) parts.push(`Пол ребёнка: ${ctx.childGender === "boy" ? "мальчик" : "девочка"}`);
  if (ctx.age !== undefined) parts.push(`Возраст ученика: ${ctx.age} лет`);
  if (ctx.preferredCategory && ctx.preferredCategory !== "neutral") {
    parts.push(`Предпочтение по стилю: ${ctx.preferredCategory === "active" ? "активное / динамичное" : "спокойное / мягкое"}`);
  }
  if (ctx.direction) parts.push(`Выбранное направление: ${ctx.direction}`);
  if (ctx.rejectedDirections?.length) parts.push(`Уже отвергнутые направления (НЕ предлагай повторно): ${ctx.rejectedDirections.join(", ")}`);
  if (ctx.branch) parts.push(`Филиал: ${ctx.branch}`);
  if (ctx.preferredTime) {
    const map = { morning: "утром", day: "днём", evening: "вечером" };
    parts.push(`Предпочитаемое время: ${map[ctx.preferredTime]}`);
  }
  if (ctx.preferredWeekday) parts.push(`Предпочитаемый день: ${ctx.preferredWeekday}`);
  if (ctx.preferredDayType) parts.push(`День недели: ${ctx.preferredDayType === "weekend" ? "выходные" : "будни"}`);
  if (ctx.phone) parts.push(`Телефон: ${ctx.phone}`);
  if (ctx.consent !== undefined) parts.push(`Согласие на обработку данных: ${ctx.consent ? "получено" : "не получено"}`);

  if (availableSlots && availableSlots.length > 0) {
    parts.push(`\nДОСТУПНЫЕ СЛОТЫ (используй ТОЛЬКО эти, не выдумывай):`);
    for (const s of availableSlots) {
      const parts2 = [`${s.weekday} в ${s.time}`, s.branch, s.direction];
      if (s.level) parts2.push(s.level);
      if (s.teacher) parts2.push(`педагог ${s.teacher}`);
      parts.push(`— id=${s.id}: ${parts2.join(", ")}`);
    }
  }

  if (parts.length === 0) return "";
  return `\nКОНТЕКСТ СЕССИИ (что мы уже знаем):\n${parts.join("\n")}\n`;
}

