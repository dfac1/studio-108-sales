export function buildStepPrompt(step: StepId, ctx: SalesSessionContext, availableSlots?: AvailableSlot[]): string {
  return `${BASE_RULES}\n${formatContext(ctx, availableSlots)}\n${STEPS[step]}`;
}

export function buildInitialPrompt(): string {
  return buildStepPrompt("ask_name", EMPTY_CONTEXT);
}

