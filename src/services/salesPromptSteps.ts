// ═══════════════════════════════════════════════════════════

export interface ParsedTransition {
  nextStep: StepId | "same";
  contextUpdate: Partial<SalesSessionContext>;
}

const STEP_IDS: ReadonlySet<string> = new Set([
  "ask_name", "ask_learner", "ask_age", "ask_direction", "ask_branch",
  "offer_slot", "ask_phone", "ask_consent", "booked", "handoff", "same"
]);

export function parseTransition(text: string): ParsedTransition | null {
  // Маркер должен быть в конце ответа: [→<step>:{<json>}]
  const match = text.match(/\[→([a-z_]+):(\{[\s\S]*?\})\]\s*$/u);
  if (!match) return null;
  const stepRaw = match[1];
  if (!STEP_IDS.has(stepRaw)) return null;
  try {
    const contextUpdate = JSON.parse(match[2]) as Partial<SalesSessionContext>;
    return { nextStep: stepRaw as StepId | "same", contextUpdate };
  } catch {
    return null;
  }
}

export function stripTransitionMarker(text: string): string {
  return text.replace(/\[→[a-z_]+:\{[\s\S]*?\}\]\s*$/u, "").trim();
}
